#!/usr/bin/env node
/**
 * Exports the prototype's obligation content as a Clause Map pack (packs/as9100d-demo.pack.json) and the
 * source-verification record (data/source-verification-record.json) plus a human-readable designator review
 * (CLAUSE-DESIGNATOR-REVIEW.md). Content stays authored by Conform-Edge: no standard text is reproduced.
 * The generated verification record is all PENDING; only a human reviewer can change a result to VERIFIED.
 */
'use strict';
const fs = require('fs'), path = require('path');
const Data = require('../src/synthetic-data.js');
const root = path.join(__dirname, '..');
const clauseOf = ref => ref.replace(/\(.*$/, '');

const byClause = {};
Data.OBLIGATIONS.forEach(ob => { (byClause[clauseOf(ob.ref)] = byClause[clauseOf(ob.ref)] || []).push(ob); });
const items = Object.keys(byClause).map(c => {
  const obs = byClause[c], first = obs[0];
  const appliesWhen = first.appliesWhen;
  return {
    itemId: 'AS9100D-' + c + '-01', clauseRef: c, groupId: 'demo',
    label: obs.map(o => o.label).join('; '),
    intent: first.intent, question: first.objective,
    evidence: first.evidenceExpected.slice(), ncPattern: first.weaknesses[0],
    findingStem: 'Objective evidence shows the requirement is not met: {evidence}. The intent of clause ' + c + ' is not met.',
    appliesWhen,
    obligations: obs.map(o => ({ obligationId: o.id, paragraph: o.ref, attributes: o.attributes.map(a => a.id), relatedObligations: o.related.slice() }))
  };
});
const pack = {
  schemaVersion: '1.0.0', packId: 'as9100d-demo',
  source: { designation: Data.CLAUSE_INDEX.source, revision: Data.CLAUSE_INDEX.edition, publisher: 'SAE / IAQG', sourceType: 'standard', publicDomain: false,
            verification: { status: 'UNVERIFIED' } },
  mapVersion: Data.PACK_VERSION.replace(/-proto$/, ''), effectiveDate: '2026-10-11',
  changelog: ['0.2.0 — Prototype demonstration obligations (5). Not a validated comprehensive audit pack.'],
  license: { owner: 'Conform-Edge Quality Consulting LLC', statement: 'Intent-based audit content authored by Conform-Edge. This pack contains no reproduction of AS9100D requirement text, notes, definitions, or annexes.', externalDocumentNotice: 'AS9100D is published by SAE/IAQG. Each user must hold their own licensed copy.' },
  appliesWhen: { certificationsAny: ['AS9100D'] },
  groups: [{ groupId: 'demo', label: 'Prototype demonstration', order: 1 }],
  items
};
fs.mkdirSync(path.join(root, 'packs'), { recursive: true });
fs.writeFileSync(path.join(root, 'packs', 'as9100d-demo.pack.json'), JSON.stringify(pack, null, 2));

// verification record: pack version must equal the pack's mapVersion
const rec = Data.VERIFICATION.map(v => Object.assign({}, v, { packVersion: pack.mapVersion }));
fs.mkdirSync(path.join(root, 'data'), { recursive: true });
fs.writeFileSync(path.join(root, 'data', 'source-verification-record.json'), JSON.stringify(rec, null, 2));
fs.writeFileSync(path.join(root, 'data', 'as9100d-clause-index.sample.json'), JSON.stringify(Data.CLAUSE_INDEX, null, 2));

// human-readable designator review (every designator in the index, where used, and its status)
const used = {};
Data.OBLIGATIONS.forEach(o => { const c = clauseOf(o.ref); (used[c] = used[c] || []).push(o.ref); });
Data.world.actions.forEach(() => {});
const rows = Object.keys(Data.CLAUSE_INDEX.clauses).sort((a, b) => a.localeCompare(b, undefined, { numeric: true })).map(c => {
  const e = Data.CLAUSE_INDEX.clauses[c];
  const para = e.paragraphs === null ? 'not catalogued' : e.paragraphs ? e.paragraphs.map(p => '(' + p + ')' + ((e.subs && e.subs[p]) ? '[' + e.subs[p].map(s => '(' + s + ')').join('') + ']' : '')).join(' ') : '—';
  const v = e.verification ? e.verification.status + ' (' + e.verification.scope + ', ' + e.verification.by + ', ' + e.verification.date + ')' : 'UNVERIFIED';
  return `| ${c} | ${e.title} | ${para} | ${(used[c] || []).join(', ') || '—'} | ${v} |`;
});
const md = `# Clause Designator Review — ${Data.CLAUSE_INDEX.source} ${Data.CLAUSE_INDEX.edition}

Generated by \`tools/export-demo-pack.js\`. **No designator here is verified against the controlled source.** The only independent check on record is the owner's directive of 2026-10-11 confirming the *titles* of 8.5.1.1, 8.5.1.2 and 8.5.1.3. Paragraph (lettered/numbered) structure and authored interpretations are unverified for every row.

Rules: do not release on developer recollection, model-generated interpretation or third-party summaries; verify against the controlled, licensed edition; do not manufacture designators where the source is not organised that way. A verified identifier does not establish that the authored interpretation is correct; both are recorded separately in \`data/source-verification-record.json\`.

| Clause | Title (Conform-Edge descriptor) | Paragraphs / subdivisions in index | Obligations using it | Verification |
|---|---|---|---|---|
${rows.join('\n')}

## Corrections made on 2026-10-11
- 8.5.1.1 = control of equipment, tools and software programs; 8.5.1.2 = validation and control of special processes; 8.5.1.3 = production process verification (owner-checked, title level). This build already used that mapping (8.5.1.2 for the special-process obligation). The **Phase B prototype in the framework folder labels 8.5.1.3 as "Validation of special processes"; that is wrong.** That file is outside this workstream's write boundary and was not changed; it must not be reused for content.
- Index title for 8.5.1.1 corrected to include "software programs".

## Open for the controlled-source review
Lettered paragraphs for 7.1.5.2 (a–c), 7.2 (a–d), 8.4.2 (a–d, and (c)(1)–(2)); parent/child structure for 8.1, 8.5, 8.7, 9.2, 10.2; whether 7.1.5.2 / 8.4.2 / 7.2 carry additional aerospace paragraphs in this edition.
`;
fs.writeFileSync(path.join(root, 'CLAUSE-DESIGNATOR-REVIEW.md'), md);

// verification package: one worksheet per obligation for the human reviewers (blank by design; nothing is pre-approved)
const vdir = path.join(root, 'verification-package'); fs.mkdirSync(vdir, { recursive: true });
Data.OBLIGATIONS.forEach(ob => {
  const sheet = `# Verification worksheet — ${ob.id} (${ob.ref})
**Pack version:** ${pack.mapVersion} · **Source:** ${Data.CLAUSE_INDEX.source} ${Data.CLAUSE_INDEX.edition} · **Status:** NOT VERIFIED — all states pending
**Authored by:** AI-assisted draft (Claude). Not self-approvable. Reviewers and the final approver must be named humans, and nobody approves what they authored.
Record outcomes in \`data/source-verification-record.json\` (entry for \`${ob.id}\`). Keep the evidence referenced by each \`evidenceRef\` (e.g. a dated copy-reference note, not licensed text).

## A. Source identity (controlled copy)
- Source identity and edition: ________   Controlled-copy identifier: ________   (record in \`source\`)

## B. Clause hierarchy — state \`clauseHierarchy\`
Draft reference: **${ob.ref}** (index: ${JSON.stringify(Data.CLAUSE_INDEX.clauses[ob.ref.replace(/\(.*$/, '')] || {})})
- [ ] Clause number and title confirmed against the controlled copy
- [ ] Every lettered / numbered subdivision confirmed to exist **as organised in the source** (do not accept a designator the source does not use)
- [ ] Parent / child relationship confirmed (the obligation sits at this level, not a parent)
- Reviewer: ________  Date: ________  Evidence ref: ________  Result: VERIFIED / REJECTED / PENDING

## C. Interpretation — state \`interpretation\` (separate from B)
Authored intent: ${ob.intent}
Authored aspects: ${ob.attributes.map(a => a.id + ' ' + a.text).join(' | ')}
Authored Should Be (paraphrase): ${ob.shouldBe}
- [ ] Intent is an accurate, independently worded reading of the requirement (no copied text, notes, or definitions)
- [ ] Each aspect is supported by the source and none is an invented obligation
- [ ] Should Be paraphrase is accurate and does not add or drop a requirement
- Reviewer: ________  Date: ________  Evidence ref: ________  Result: VERIFIED / REJECTED / PENDING

## D. Intended outcome — state \`intendedOutcome\`
Authored objective: ${ob.objective}
- [ ] The outcome the obligation is meant to achieve is correctly stated
- Reviewer: ________  Date: ________  Evidence ref: ________  Result: ________

## E. Applicability — state \`applicability\`
Authored conditions: ${JSON.stringify(ob.appliesWhen)}
- [ ] Conditions under which the obligation applies (and does not) are correct; exclusions are justified
- Reviewer: ________  Date: ________  Evidence ref: ________  Result: ________

## F. Verification activities and alternatives (review aid, not a release state)
Steps: ${ob.steps.join(' · ')}
Alternative-explanation checks: ${ob.rebuttalChecks.map(r => r.text).join(' · ') || 'none defined'}
- [ ] Reviewer agrees an auditor can reach a defensible conclusion by these steps, and valid alternative controls are not treated as findings.

## G. Final technical approval — \`finalApproval\`
Approver (initial AS9100D production pack: Brian Olea): ________  Date: ________  Status: APPROVED / REJECTED / PENDING  Evidence ref: ________
`;
  fs.writeFileSync(path.join(vdir, 'WORKSHEET-' + ob.id + '.md'), sheet);
});

console.log('wrote packs/as9100d-demo.pack.json, data/source-verification-record.json, CLAUSE-DESIGNATOR-REVIEW.md');
